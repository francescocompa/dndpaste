// Writes src/sources.ts: the Unearthed Arcana source codes a paste may cite (D205), each with its title. Codes and
// titles only, never rules text. Run it by hand when the local Unearthed Arcana collection updates, then commit:
//   node scripts/ua-sources.mjs <unearthed-arcana folder>
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) { console.error("usage: node scripts/ua-sources.mjs <unearthed-arcana folder>"); process.exit(2); }
const files = [];
const walk = (dir) => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (f.endsWith(".json")) files.push(p); } };
walk(root);
const byCode = new Map();
for (const f of files) {
  let j;
  try { j = JSON.parse(readFileSync(f, "utf8")); } catch { continue; }
  for (const s of j?._meta?.sources ?? []) if (typeof s.json === "string" && s.json) byCode.set(s.json, String(s.full ?? s.json));
}
const rows = [...byCode].sort(([a], [b]) => (a.toLowerCase() < b.toLowerCase() ? -1 : a.toLowerCase() > b.toLowerCase() ? 1 : 0));
const q = (s) => JSON.stringify(s);
const out = `/**
 * Unearthed Arcana source codes a paste may cite (D205), each with its title: playtest material that no slot table
 * holds. The checker accepts a name with one of these codes at info, and /codes may list them. Codes and titles only.
 * Generated by scripts/ua-sources.mjs from a local Unearthed Arcana collection; do not edit by hand.
 */
export interface UaSource { code: string; title: string }

export const UA_SOURCES: readonly UaSource[] = [
${rows.map(([c, t]) => `  { code: ${q(c)}, title: ${q(t)} },`).join("\n")}
];
`;
writeFileSync(new URL("../src/sources.ts", import.meta.url), out);
console.log(`src/sources.ts: ${rows.length} codes`);
