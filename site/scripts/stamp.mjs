// The build stamp: the library version from the root package.json, the git commit and its date, written to
// src/build.gen.ts (gitignored) for the Worker (the page foot, GET /version) and the client bundles (the update
// check). Run by build-client.mjs, so before `wrangler dev`, `wrangler deploy` and `npm run verify`.
// The file is rewritten only when its text changes: `wrangler dev` watches src/, and a rewrite on every build
// would loop. A tree with uncommitted changes to site/ or src/ gets a "+" after the commit (dev builds).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const site = fileURLToPath(new URL("..", import.meta.url));
export const STAMP_FILE = join(site, "src/build.gen.ts");

const git = (...args) => {
  try {
    return execFileSync("git", args, { cwd: site, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
};

/** `{ version, commit, date }`; outside a git checkout the commit is "nogit" and the date empty. */
export function stamp() {
  const { version } = JSON.parse(readFileSync(join(site, "../package.json"), "utf8"));
  const commit = git("rev-parse", "--short=7", "HEAD");
  if (!commit) return { version, commit: "nogit", date: "" };
  const dirty = git("status", "--porcelain", "--untracked-files=no", "--", ".", "../src");
  return { version, commit: dirty ? `${commit}+` : commit, date: git("log", "-1", "--format=%cs") ?? "" };
}

export function stampSource(s) {
  return `// Generated by scripts/stamp.mjs at build time. Do not edit; not committed.\n` +
    `export const BUILD = ${JSON.stringify(s)} as const;\n`;
}

/** Writes src/build.gen.ts when its text changes; returns the stamp. */
export function writeStamp(s = stamp()) {
  const text = stampSource(s);
  if (!existsSync(STAMP_FILE) || readFileSync(STAMP_FILE, "utf8") !== text) writeFileSync(STAMP_FILE, text);
  return s;
}
