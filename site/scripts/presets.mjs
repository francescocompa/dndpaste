// Writes site/src/presets.ts, the table behind the form's "Start a build" (D121–D125): for each core class in 2014
// (PHB) and 2024 (XPHB), the keys a build owes at each class level, the way the checker counts them (src/check.ts,
// owed-slot ledger), and how many picks each counted line expects there (the editor's ghost counts, D129–D133).
// Key names and numbers only, and the names of features with a pick (D313): no names of subclasses, spells or
// options, no rules text.
// Read from the committed SRD slot table and supplement, so no new data leaves the repo (D125). Run it by hand after
// either file changes, then commit the diff (D115); test/preset.test.ts fails while the committed file is stale:
//   node site/scripts/presets.mjs [out file]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { presetRows } from "../src/presetrows.ts";

const load = (rel) => JSON.parse(readFileSync(fileURLToPath(new URL(`../../data/${rel}`, import.meta.url)), "utf8"));
const slots = load("srd/slots.json");
const sup = load("supplement.json");
const EDITION = { PHB: "2014", XPHB: "2024" };

// The rows themselves: src/presetrows.ts, shared with the browser for a visitor's own classes (D246).
const { rows, species, backgrounds } = presetRows(slots, sup, (e) => e.core && e.source in EDITION);

const q = (v) => JSON.stringify(v);
const out = process.argv[2] ?? fileURLToPath(new URL("../src/presets.ts", import.meta.url));
writeFileSync(out, `/**
 * Class presets for the form's "Start a build" (D121–D125): the keys each core class owes at each class level, as the
 * checker counts them, and the picks each counted line expects (the editor's ghost counts, D129–D133). Key names and
 * numbers only, a species' lineage trait name (D211) and the names of class features with a pick (D313).
 * Generated by site/scripts/presets.mjs from the committed SRD
 * slot table; do not edit by hand.
 */
export type Edition = "2014" | "2024";
export interface ClassPreset {
  name: string;
  /** PHB for 2014, XPHB for 2024; a class from your own sources keeps its book (D246). */
  source: string;
  /** A class from your own sources: its edition, when known. */
  edition?: Edition;
  /** Extra keys at class level 1 when this is the build's first class (skills, starting gear). */
  first: readonly string[];
  /** Extra keys at class level 1 when the class is taken later (multiclass skills). */
  multi: readonly string[];
  /** owes[k - 1]: the keys owed at class level k, 1–20. */
  owes: readonly (readonly string[])[];
  /** The keys the editor counts for this class (D129); a key not here gets no ghost. */
  counted: readonly string[];
  /** Skills to choose at class level 1: [as the first class, as a later class]. */
  skills: readonly [number, number];
  /** counts[k - 1]: picks each counted key expects at class level k (a total for Masteries and Prepared); absent is 0. */
  counts: readonly Readonly<Record<string, number>>[];
  /** features[k]: the features with a pick at class level k, by name (D313); the \`Feature\` line names them. */
  features?: Readonly<Record<number, readonly string[]>>;
}

export const PRESETS: readonly ClassPreset[] = [
${rows.map((r) => `  { name: ${q(r.name)}, source: ${q(r.source)}, first: ${q(r.first)}, multi: ${q(r.multi)},\n    owes: ${q(r.owes)},\n    counted: ${q(r.counted)}, skills: ${q(r.skills)},\n    counts: ${q(r.counts)}${r.features ? `,\n    features: ${q(r.features)}` : ""} },`).join("\n")}
];

/** D211: the lines a species owes: [key, picks] for a counted key, [\`Species\`, trait name] for its lineage (in the Species
 *  line's brackets, D291), [\`Feature\`, name] for another species feature with picks. */
export interface SpeciesPreset { name: string; source: string; edition?: Edition; lines: readonly (readonly [string, number | string])[] }

export const SPECIES_PRESETS: readonly SpeciesPreset[] = [
${species.map((r) => `  { name: ${q(r.name)}, source: ${q(r.source)}, lines: ${q(r.lines)} },`).join("\n")}
];

/** D351: what a background's block owes: the abilities its \`Scores\` increase takes (2024; none in 2014), and
 *  [key, picks] for the Skills, Tools and Languages it leaves to choose. */
export interface BackgroundPreset { name: string; source: string; abilities: readonly string[]; lines: readonly (readonly [string, number])[] }

export const BACKGROUND_PRESETS: readonly BackgroundPreset[] = [
${backgrounds.map((r) => `  { name: ${q(r.name)}, source: ${q(r.source)}, abilities: ${q(r.abilities)}, lines: ${q(r.lines)} },`).join("\n")}
];
`);
console.log(`${out}: ${rows.length} presets (${rows.filter((r) => r.source === "PHB").length} 2014, ${rows.filter((r) => r.source === "XPHB").length} 2024)`);
