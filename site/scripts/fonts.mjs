// Copies IBM Plex Sans + Mono (OFL 1.1, via @fontsource) into public/assets/fonts and writes fonts.css.
// Latin + Latin Extended, weights 400 and 600, woff2 only. Self-hosted: the site never calls Google Fonts (D81).
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = root + "public/assets/fonts/";
mkdirSync(out, { recursive: true });
const families = ["ibm-plex-sans", "ibm-plex-mono"];
const subsets = ["latin", "latin-ext"];
const weights = ["400", "600"];
let css = "/* IBM Plex Sans and IBM Plex Mono, SIL Open Font License 1.1 (OFL.txt). Generated by scripts/fonts.mjs. */\n";

for (const fam of families) {
  const pkg = `${root}node_modules/@fontsource/${fam}/`;
  for (const w of weights) {
    const src = readFileSync(`${pkg}${w}.css`, "utf8");
    for (const sub of subsets) {
      const file = `${fam}-${sub}-${w}-normal.woff2`;
      const block = src.split("/* ").find((b) => b.startsWith(`${fam}-${sub}-${w}-normal */`));
      const range = block && /unicode-range:\s*([^;]+);/.exec(block);
      if (!range) throw new Error(`no unicode-range for ${file}`);
      const name = fam === "ibm-plex-sans" ? "IBM Plex Sans" : "IBM Plex Mono";
      copyFileSync(`${pkg}files/${file}`, out + file);
      css += `@font-face { font-family: "${name}"; font-style: normal; font-weight: ${w}; font-display: swap;\n` +
        `  src: url(/assets/fonts/${file}) format("woff2");\n  unicode-range: ${range[1].trim()}; }\n`;
    }
  }
}
copyFileSync(`${root}node_modules/@fontsource/ibm-plex-sans/LICENSE`, out + "OFL.txt");
writeFileSync(root + "public/assets/fonts.css", css);
console.log("fonts: wrote", families.length * subsets.length * weights.length, "faces");
